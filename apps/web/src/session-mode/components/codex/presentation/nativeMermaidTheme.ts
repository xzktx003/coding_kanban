function flowchartCss(theme: (typeof variables)["dark" | "light"]) {
  return `
.node text {font-size:14px;font-weight:600;letter-spacing:normal;fill:${theme.flowchartTextColor};}
.edgeLabels text {font-size:13px;font-weight:600;letter-spacing:-0.08px;fill:${theme.flowchartTextColor};}
.node tspan[font-weight="normal"],.edgeLabels tspan[font-weight="normal"] {font-weight:600;}
.edgeLabel .label rect {opacity:1;rx:13px;ry:13px;fill:${theme.flowchartEdgeLabelColor};stroke:${theme.flowchartEdgeLabelBorderColor};stroke-width:1px;}
.node rect,.node circle,.node ellipse,.node polygon,.node path {fill:${theme.flowchartNodeColor};stroke:${theme.flowchartNodeBorderColor};stroke-width:1px;}
.node rect {rx:16px;ry:16px;}
.node.mermaid-decision .label-container {fill:${theme.flowchartDecisionColor};stroke:${theme.flowchartLineColor};stroke-dasharray:2 2;}
.edgePaths .flowchart-link {stroke:${theme.lineColor};stroke-width:1px;stroke-linecap:round;stroke-linejoin:round;}
.marker {fill:${theme.lineColor};stroke:${theme.lineColor};}
`;
}

export function nativeMermaidConfig(theme: "dark" | "light", source = "") {
  const themeVariables = variables[theme];
  const improvedFlowchart = /^\s*(?:flowchart|graph)\b/i.test(
    source
      .split(/\r?\n/)
      .find((line) => line.trim() && !line.trim().startsWith("%%")) ?? "",
  );
  return {
    startOnLoad: false,
    securityLevel: "strict",
    suppressErrorRendering: true,
    theme: "base",
    layout: improvedFlowchart ? "chatgpt-flowchart" : "codex-elk",
    flowchart: { useMaxWidth: false },
    darkMode: theme === "dark",
    fontFamily: themeVariables.fontFamily,
    htmlLabels: false,
    themeVariables,
    themeCSS: improvedFlowchart ? flowchartCss(themeVariables) : undefined,
  } satisfies NonNullable<MermaidOptions["config"]>;
}
